"""Regenerate hardware constants and bare-metal fixture. Run from any directory."""
from pathlib import Path
import sys
import json
import hashlib

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from cycle_sim.fixtures import load_int8_fixture

def main():
    target = Path(__file__).resolve().parents[1]
    f = load_int8_fixture()
    arrays = {name: f[key].astype(dtype).tobytes() for name, key, dtype in (
        ('fixture_image', 'image', 'i1'), ('fixture_weights', 'weights', 'i1'),
        ('fixture_bias', 'bias', '<i4'), ('fixture_quant', 'quant', '<i4'),
        ('fixture_expected', 'expected_int8', 'i1'))}
    header = ['/* Generated by tools/export_fixture.py. Do not edit. */',
              '#ifndef CONV0_FIXTURE_DATA_H', '#define CONV0_FIXTURE_DATA_H', '#include <stdint.h>']
    for name, data in arrays.items():
        header.append(f'static const uint8_t {name}[{len(data)}] __attribute__((aligned(64))) = {{')
        header += ['  ' + ','.join(f'0x{x:02x}' for x in data[i:i+24]) + ',' for i in range(0, len(data), 24)]
        header.append('};')
    header.append('#endif')
    (target/'cpu').mkdir(exist_ok=True, parents=True)
    (target/'src').mkdir(exist_ok=True, parents=True)
    (target/'cpu/fixture_data.h').write_text('\n'.join(header)+'\n', encoding='ascii')
    sv = ['// Generated: fixed pretrained Conv0 quantization, signed INT32 -> ReLU INT8.',
          'package conv0_quant_pkg;']
    for func, values in [('quant_m', f['multiplier']), ('quant_s', f['shift'])]:
        sv += [f'function automatic integer {func}(input integer channel);', 'case (channel)']
        sv += [f'{i}: {func} = {int(v)};' for i,v in enumerate(values)]
        sv += [f'default: {func} = 0;', 'endcase', 'endfunction']
    sv += ['function automatic logic [7:0] quant_byte(input integer addr);',
           'integer word_value;', 'begin',
           'word_value = ((addr/4)%2 == 0) ? quant_m(addr/8) : quant_s(addr/8);',
           'quant_byte = (word_value >> (8*(addr%4))) & 255;', 'end', 'endfunction', 'endpackage']
    (target/'src/conv0_quant_pkg.sv').write_text('\n'.join(sv)+'\n', encoding='ascii')
    (target/'cpu/fixture_manifest.json').write_text(json.dumps({
        'source': f['identity'], 'payloads': {k: {'bytes':len(v), 'sha256': hashlib.sha256(v).hexdigest()}
                                            for k,v in arrays.items()}}, indent=2)+'\n')
    print('Generated quantization package, C fixture, and checksum manifest.')

if __name__ == '__main__':
    main()
