"""Check the wrapper's documented packing/feed schedule against the Python MXU.

This does not execute RTL or verify AXI handshakes. The HDL testbench is needed
for those checks. No files are generated by this script.
"""
import struct

from gen_mxu_vectors import MxuModel


ROWS, COLS = 27, 26


def check(n):
    weights = [[((r * 13 + c * 7) % 255) - 127 for c in range(COLS)]
               for r in range(ROWS)]
    inputs = [[((p * 11 + r * 3) % 255) - 127 for r in range(ROWS)]
              for p in range(n)]
    weight_wire = bytes(w & 255 for row in weights for w in row)
    input_wire = bytes(x & 255 for row in inputs for x in row)
    assert len(weight_wire) == 702 and len(input_wire) == n * 27

    # Check byte addressing across stream-beat boundaries into wide words.
    for wire, width, matrix in [(weight_wire, COLS, weights),
                                 (input_wire, ROWS, inputs)]:
        reconstructed = [[None] * width for _ in matrix]
        for offset in range(0, len(wire), 32):
            beat = wire[offset:offset + 32]
            keep = (1 << len(beat)) - 1
            assert keep.bit_count() == len(beat)
            for lane, value in enumerate(beat):
                row, column = divmod(offset + lane, width)
                reconstructed[row][column] = value if value < 128 else value - 256
        assert reconstructed == matrix

    model = MxuModel(ROWS, COLS)
    captured = [[] for _ in range(COLS)]
    first_input = ROWS + 2
    for edge in range(first_input + n + ROWS + COLS + 4):
        loading = edge < ROWS
        p = edge - first_input
        valid = 0 <= p < n
        outs = model.step(inputs[p] if valid else [0] * ROWS,
                          int(valid), int(p == 0), int(loading),
                          weights[ROWS - 1 - edge] if loading else [0] * COLS)
        for c, (value, is_valid) in enumerate(outs):
            if is_valid:
                index = len(captured[c])
                assert edge == first_input + index + ROWS - 1 + c
                assert value == sum(inputs[index][r] * weights[r][c]
                                    for r in range(ROWS))
                captured[c].append(value)
    assert all(len(bank) == n for bank in captured)
    results = [captured[c][p] for p in range(n) for c in range(COLS)]
    output_wire = b''.join(struct.pack('<i', value) for value in results)
    assert len(output_wire) == n * 104
    assert list(struct.unpack(f'<{n * COLS}i', output_wire)) == results
    print(f'PASS N={n}: {n * COLS} results; '
          f'payloads {len(weight_wire)}/{len(input_wire)}/{len(output_wire)} bytes; '
          f'final output KEEP=0x{((1 << ((len(output_wire)-1)%32+1))-1):08x}')


if __name__ == '__main__':
    for count in (1, 2, 3, 64):
        check(count)
    print('Python packing/schedule checks only; RTL simulation is still required.')
