"""Reproduce analytic latency budgets and network workloads; no HDL execution.

Run from any directory. Uses the existing full-network export manifest.
All bandwidth, CPU overhead, and clock numbers below are assumptions.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path

PROJECT=Path(__file__).resolve().parents[2]

def budget(mode, bandwidth, setup_us, other_us, clock_mhz=100):
    # Sequential packets; within each packet loader and link may overlap.
    packets=[3072,702,104,208] if mode=='cold' else [3072]
    preload=sum(max(n/bandwidth, ((n+15)//16)/clock_mhz) for n in packets)
    # Output cannot begin at START. 34 cycles is an analytic pipeline allowance,
    # not a cycle-correlated count from simulation. The max avoids double-counting
    # compute and output drain. Finite FIFO/burst effects are not modeled here.
    run=max(1217/clock_mhz, 34/clock_mhz+26624/bandwidth)
    return dict(mode=mode,bandwidth_MB_s=bandwidth,setup_per_submission_us=setup_us,
        other_cpu_completion_us=other_us,submissions=len(packets)+1,
        preload_floor_us=preload,overlapped_run_floor_us=run,
        analytic_budget_us=preload+run+(len(packets)+1)*setup_us+other_us)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--manifest',type=Path,default=PROJECT/'resnet8/artifacts/export/manifest.json')
    p.add_argument('--out',type=Path,default=PROJECT/'arch1_broadcast_832/reports/meeting_2026_10_20')
    a=p.parse_args()
    source=a.manifest.read_bytes(); manifest=json.loads(source)
    rows=[]
    for layer in manifest['layers']:
        c=layer['config']; op=layer['op']
        inp=c['height']*c['width']*c['cin']
        out=c['out_height']*c['out_width']*c['cout']
        macs=out*c['kernel']**2*c['cin'] if op=='conv' else (c['cin']*c['cout'] if op=='dense' else 0)
        # One kernel dispatch per exported operation, inputs read from DDR and
        # output written to DDR; adds read two equal-size branches, ReLU fused.
        traffic=inp*(2 if op=='add' else 1)+out
        rows.append(dict(layer=layer['name'],op=op,input_bytes=inp,output_bytes=out,
            mac_terms=macs,weights_bytes=c['weights_count'],bias_bytes=4*c['bias_count'],
            quant_bytes=8*c['quant_count'],unfused_activation_DDR_bytes=traffic))
    assert len(rows)==14 and rows[0]['mac_terms']==718848 and rows[-1]['mac_terms']==1040
    budgets=[budget(mode,bw,s,other) for mode in ('cold','warm')
        for bw in (500,1000,2000) for s in (0,0.5,2,5) for other in (0,2,5,10)]
    a.out.mkdir(parents=True,exist_ok=True)
    for name,data in [('layer_workload.csv',rows),('latency_sensitivity.csv',budgets)]:
        with (a.out/name).open('w',newline='',encoding='utf-8') as f:
            w=csv.DictWriter(f,fieldnames=list(data[0])); w.writeheader(); w.writerows(data)
    totals={key:sum(r[key] for r in rows) for key in ('mac_terms','weights_bytes','bias_bytes','quant_bytes','unfused_activation_DDR_bytes')}
    totals.update(export_manifest_sha256=hashlib.sha256(source).hexdigest(),
        conv0_mac_fraction=rows[0]['mac_terms']/totals['mac_terms'],
        resident_network_external_activation_bytes=3072+10)
    (a.out/'analysis_summary.json').write_text(json.dumps(totals,indent=2)+'\n',encoding='utf-8')
    md=['# Analytic latency and full-network workload','',
        'Generated by `arch1_broadcast_832/tools/meeting_analysis.py`. These are arithmetic estimates, not RTL or board measurements.','',
        '## Concrete host sequence','',
        'Cold: 4 MM2S submissions + 1 S2MM submission. Warm: 1 MM2S + 1 S2MM. The hardware retains parameters, but the software still copies the image, maintains caches, programs DMA/control, and polls.','',
        'For each packet, preload floor = max(bytes / bandwidth, ceil(bytes / 16) / 100 MHz). Sum packets because the current host loads them sequentially. Run floor = max(12.17 us, 0.34 us + 26624 / bandwidth). The 0.34 us first-output allowance is analytic, not an observed counter. Add one assumed setup cost per submission and a separate combined CPU/completion cost. Bandwidth in decimal MB/s equals bytes/us.','',
        'This deliberately simplified overlap model excludes burst gaps, packet startup, detailed FIFO stalls, DDR arbitration and clock crossing. It is a sensitivity budget with optimistic hardware floors, not a replacement for the Python cycle model or a prediction interval. Do not add these costs to 19.47 us: that model already includes its own setup/completion assumptions.','',
        '| Assumed bandwidth MB/s | Setup us/submission | Cold budget us | Warm budget us |',
        '|---:|---:|---:|---:|']
    for bw in (500,1000,2000):
        for setup in (0,0.5,2,5):
            md.append(f'| {bw} | {setup:g} | {budget("cold",bw,setup,5)["analytic_budget_us"]:.3f} | {budget("warm",bw,setup,5)["analytic_budget_us"]:.3f} |')
    md+=['','Table assumes an additional 5 us combined CPU/cache/completion allowance. This is an illustrative input, not a measured value. CSV also sweeps 0, 2, and 10 us. At 2 GB/s, output serialization alone is 13.312 us. Warm saves only 1,014 payload bytes relative to cold, but also avoids three DMA submissions.','',
        '## Workload from the existing exported network','',
        '| Operation | MAC terms | Weight bytes | Input bytes (one branch) | Output bytes | Unfused activation DDR bytes |',
        '|---|---:|---:|---:|---:|---:|']
    for r in rows:
        md.append(f'| {r["layer"]} | {r["mac_terms"]:,} | {r["weights_bytes"]:,} | {r["input_bytes"]:,} | {r["output_bytes"]:,} | {r["unfused_activation_DDR_bytes"]:,} |')
    md+=['',f'Total convolution/dense MAC terms: **{totals["mac_terms"]:,}**. Conv0 is **{totals["conv0_mac_fraction"]*100:.2f}%**. Adds, pooling, requantization and control are additional work, not counted as convolution MAC terms.',
        f'Weights: **{totals["weights_bytes"]:,} bytes**, bias: **{totals["bias_bytes"]:,} bytes**, quantization: **{totals["quant_bytes"]:,} bytes**. Layer descriptors are additional.',
        f'One DDR dispatch per operation moves **{totals["unfused_activation_DDR_bytes"]:,} activation bytes/inference**, excluding parameters. Keeping all intermediate activations on chip reduces the external activation payload to **3,082 bytes** (image + ten INT8 logits), under that hypothetical architecture. Neither architecture is implemented here.','',
        '## Storage and architecture implications','',
        'A conservative three-buffer INT8 allocation at the largest feature-map size needs 3 x 26,624 = 79,872 bytes: retained residual input, intermediate, and destination. Block2 needs at most 26,624 + 13,312 + 13,312 = 53,248 logical bytes with deliberate buffer reuse; Block3 needs 13,312 + 6,656 + 6,656 = 26,624. This is an activation capacity sketch, not a physical banking/port plan. Accumulators, weights, FIFOs, alignment and replication require additional storage.',
        'The current Conv0 input replication already stores 32 x 3,072 = 98,304 logical bytes; do not extrapolate that replication strategy to 26/52/104-channel tensors. Later layers should explore channel tiling and line/tile buffers, then reuse a compute engine across layers. Residual sources must survive until both branches are ready. Preserve signed outputs before residual addition and align both branches to the add output scale before summing.',
        'Stride-2 SAME padding is asymmetric for the frozen even-sized inputs: 3x3 uses top/left=0 and bottom/right=1. The Conv0 symmetric padding address generator is not directly reusable unchanged.',
        'Changing the fixed Conv0 quantization package requires a hardware rebuild. A reusable multi-layer engine needs either layer-selectable compiled constants or runtime quantization, with a new resource/timing study.','',
        '## Measurements that resolve the uncertainty','',
        'Keep the existing whole-request timer as the headline. In a separate diagnostic run timestamp copy/cache work, each MM2S submit/wait, S2MM setup, START-to-DMA-completion, and final invalidate. Extra timer reads perturb short requests, so do not silently substitute the instrumented result for the baseline. Correlate hardware run/raw/first-output counters and output stalls; record actual PL clock, CPU build settings and source/fixture hashes.','',
        f'Source manifest SHA-256: `{totals["export_manifest_sha256"]}`.']
    (a.out/'ANALYSIS.md').write_text('\n'.join(md)+'\n',encoding='utf-8')
    print(json.dumps(totals,indent=2))
    print(f'Wrote {len(budgets)} analytic scenarios and {len(rows)} layer records to {a.out}')

if __name__=='__main__': main()
